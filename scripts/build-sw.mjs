// Emits public/sw.js from sw/service-worker.js with this build's version stamped in.
// Runs automatically before `npm run build` (prebuild). Every build gets a distinct version, so
// browsers see a byte-different worker after each deploy and offer the in-app "Reload" update.
//
// Version = APP_VERSION env var if set (e.g. from CI), else "<package version>+<git sha|timestamp>".
import { execSync } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";

const pkg = JSON.parse(await readFile("package.json", "utf8"));

function buildTag() {
  try {
    const sha = execSync("git rev-parse --short HEAD", { stdio: ["ignore", "pipe", "ignore"] }).toString().trim();
    const dirty = execSync("git status --porcelain", { stdio: ["ignore", "pipe", "ignore"] }).toString().trim();
    // Uncommitted builds still need a unique stamp, or a local redeploy would never update.
    return dirty ? `${sha}.${Date.now().toString(36)}` : sha;
  } catch {
    return Date.now().toString(36);
  }
}

const version = process.env.APP_VERSION || `${pkg.version}+${buildTag()}`;
const source = await readFile("sw/service-worker.js", "utf8");
const banner = `// Generated by scripts/build-sw.mjs. Do not edit; change sw/service-worker.js instead.\nconst APP_VERSION = ${JSON.stringify(version)};\n\n`;

await writeFile("public/sw.js", banner + source);
console.log(`Service worker built for ${version}`);
